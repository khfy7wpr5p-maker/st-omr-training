_HEX64_RE = re.compile(r"^[0-9a-f]{64}$")

# Ground truth is never generated by a learned model. Synthetic spatial labels
# must come from pinned renderer/transform lineage; real spatial labels require
# independent human-verified annotation.
GT_CANONICAL_MUSIC: Final[str] = "canonical_music"
GT_RENDERER_GEOMETRY: Final[str] = "pinned_renderer_geometry"
GT_DETERMINISTIC_TRANSFORM: Final[str] = "deterministic_geometry_transform"
GT_HUMAN_VERIFIED_ANNOTATION: Final[str] = "human_verified_annotation"
GT_ADMITTED_REAL_MUSICXML: Final[str] = "admitted_real_musicxml"

ALLOWED_GT_SOURCES: Final[tuple[str, ...]] = (
    GT_CANONICAL_MUSIC,
    GT_RENDERER_GEOMETRY,
    GT_DETERMINISTIC_TRANSFORM,
    GT_HUMAN_VERIFIED_ANNOTATION,
    GT_ADMITTED_REAL_MUSICXML,
)


@dataclass(frozen=True, slots=True)
class SpecialistDatasetContract:
    """One independently auditable specialist ground-truth set."""

    set_name: str
    task_id: str
    labels: tuple[str, ...]
    synthetic_ground_truth: tuple[str, ...]
    real_ground_truth: tuple[str, ...]
    geometry_required: bool

    def __post_init__(self) -> None:
        if not self.set_name.endswith("Set"):
            raise ValueError("specialist dataset names must end in 'Set'")
        if not self.task_id or not self.task_id.isascii():
            raise ValueError("task_id must be non-empty ASCII")
        if not self.labels or len(set(self.labels)) != len(self.labels):
            raise ValueError("labels must be non-empty and unique")
        if not self.synthetic_ground_truth or not self.real_ground_truth:
            raise ValueError("both synthetic and real ground-truth policies are required")
        for source in self.synthetic_ground_truth + self.real_ground_truth:
            if source not in ALLOWED_GT_SOURCES:
                raise ValueError(f"unsupported ground-truth source: {source}")
        if self.geometry_required:
            synthetic = set(self.synthetic_ground_truth)
            if GT_RENDERER_GEOMETRY not in synthetic or GT_DETERMINISTIC_TRANSFORM not in synthetic:
                raise ValueError(
                    "synthetic geometry labels require renderer geometry and deterministic transform lineage"
                )
            if GT_HUMAN_VERIFIED_ANNOTATION not in self.real_ground_truth:
                raise ValueError("real geometry labels require human-verified annotation")


@dataclass(frozen=True, slots=True)
class SpecialistTaskContract:
    """One V1 specialist inference boundary."""

    task_id: str
    dataset_name: str
    responsibility: str
    depends_on: tuple[str, ...]
    inputs: tuple[str, ...]
    outputs: tuple[str, ...]
    trainable: bool
    confidence_required: bool

    def __post_init__(self) -> None:
        if not self.task_id or not self.task_id.isascii():
            raise ValueError("task_id must be non-empty ASCII")
        if not self.dataset_name.endswith("Set"):
            raise ValueError("dataset_name must reference a specialist set")
        if not self.responsibility:
            raise ValueError("responsibility must be non-empty")
        if len(set(self.depends_on)) != len(self.depends_on):
            raise ValueError("depends_on entries must be unique")
        if not self.inputs or not self.outputs:
            raise ValueError("specialist inputs/outputs must be non-empty")
        if len(set(self.inputs)) != len(self.inputs) or len(set(self.outputs)) != len(self.outputs):
            raise ValueError("specialist inputs/outputs must be unique")
        if self.confidence_required and "confidence" not in self.outputs:
            raise ValueError("confidence-required specialist must expose confidence")


