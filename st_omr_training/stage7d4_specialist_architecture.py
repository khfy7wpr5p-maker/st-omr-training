def _canonical_json_bytes(payload: object) -> bytes:
    return json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    ).encode("ascii")


def _dataset_map() -> dict[str, SpecialistDatasetContract]:
    return {item.set_name: item for item in V1_SPECIALIST_DATASETS}


def _task_map() -> dict[str, SpecialistTaskContract]:
    return {item.task_id: item for item in V1_SPECIALIST_TASKS}


def validate_stage7d4_architecture() -> None:
    """Fail closed if the frozen specialist contract is internally inconsistent."""

    datasets = _dataset_map()
    tasks = _task_map()
    if len(datasets) != len(V1_SPECIALIST_DATASETS):
        raise ValueError("specialist dataset names must be unique")
    if len(tasks) != len(V1_SPECIALIST_TASKS):
        raise ValueError("specialist task ids must be unique")
    if set(item.task_id for item in V1_SPECIALIST_DATASETS) != set(tasks):
        raise ValueError("every specialist task must have exactly one dataset contract")
    for task in V1_SPECIALIST_TASKS:
        if task.dataset_name not in datasets:
            raise ValueError(f"unknown specialist dataset: {task.dataset_name}")
        if datasets[task.dataset_name].task_id != task.task_id:
            raise ValueError("task/dataset identity mismatch")
        for dependency in task.depends_on:
            if dependency not in tasks:
                raise ValueError(f"unknown specialist dependency: {dependency}")
            if dependency == task.task_id:
                raise ValueError("specialist task cannot depend on itself")

    # Explicit DFS cycle check keeps the execution order auditable.
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(task_id: str) -> None:
        if task_id in visited:
            return
        if task_id in visiting:
            raise ValueError("specialist dependency graph contains a cycle")
        visiting.add(task_id)
        for dependency in tasks[task_id].depends_on:
            visit(dependency)
        visiting.remove(task_id)
        visited.add(task_id)

    for task_id in tasks:
        visit(task_id)

    context = tasks["context_validation"]
    if context.trainable:
        raise ValueError("V1 context fusion must remain deterministic")
    staff_position = tasks["staff_position"]
    forbidden_pitch_outputs = {"pitch", "pitch_name", "midi", "octave", "step"}
    if forbidden_pitch_outputs.intersection(staff_position.outputs):
        raise ValueError("staff-position specialist may not authoritatively predict absolute pitch")
    if "staff_position" not in staff_position.outputs:
        raise ValueError("staff-position specialist must expose discrete staff position")

    if V1_MUSIC_POLICY["logical_staves_per_part"] != 1:
        raise ValueError("V1 must remain one logical staff per part")
    if V1_MUSIC_POLICY["rendered_staff_instances_per_page"] != "one_or_more":
        raise ValueError("V1 pages must allow repeated graphical staff instances across systems")
    if GEOMETRY_LABEL_POLICY["unlinked_or_ambiguous_renderer_element"] != "reject_specialist_sample":
        raise ValueError("ambiguous synthetic renderer geometry must fail closed")
    if GEOMETRY_LABEL_POLICY["geometry_transform_must_be_fingerprinted"] is not True:
        raise ValueError("specialist geometry transforms must be fingerprinted")
    if GEOMETRY_LABEL_POLICY["photometric_transforms_change_geometry"] is not False:
        raise ValueError("photometric transforms must not rewrite spatial labels")

    if SPLIT_POLICY["test_model_development_access"] is not False:
        raise ValueError("TEST must remain sealed from model development")
    if SPLIT_POLICY["test_specialist_dataset_derivation_during_development"] is not False:
        raise ValueError("TEST specialist labels must not be derived during development")
    if TRAINING_DATA_POLICY["ai_generated_ground_truth"] is not False:
        raise ValueError("AI-generated ground truth is forbidden")
    if TRAINING_DATA_POLICY["online_learning"] is not False or TRAINING_DATA_POLICY["automatic_learning"] is not False:
        raise ValueError("online/automatic learning is forbidden")
    if TRAINING_DATA_POLICY["teacher_correction_is_automatic_training_data"] is not False:
        raise ValueError("teacher corrections cannot become automatic training data")
    if FUSION_POLICY["learned_fusion"] is not False:
        raise ValueError("Stage 7-D4 V1 fusion must remain deterministic")


def stage7d4_architecture_payload() -> dict[str, object]:
    validate_stage7d4_architecture()
    return {
        "schema": STAGE7D4_CONTRACT_SCHEMA,
        "version": STAGE7D4_ARCHITECTURE_VERSION,
        "v1_music_policy": V1_MUSIC_POLICY,
        "geometry_label_policy": GEOMETRY_LABEL_POLICY,
        "split_policy": SPLIT_POLICY,
        "training_data_policy": TRAINING_DATA_POLICY,
        "fusion_policy": FUSION_POLICY,
        "datasets": [asdict(item) for item in V1_SPECIALIST_DATASETS],
        "tasks": [asdict(item) for item in V1_SPECIALIST_TASKS],
        "deferred_surface": DEFERRED_SPECIALIST_SURFACE,
    }


def stage7d4_architecture_fingerprint() -> str:
    return sha256(_canonical_json_bytes(stage7d4_architecture_payload())).hexdigest()


def is_sha256_hex(value: object) -> bool:
    return isinstance(value, str) and _HEX64_RE.fullmatch(value) is not None
