"""Frozen Stage 7-D4 specialist-OMR architecture contract.

This module is declarative only. It defines the V1 specialist task graph,
ground-truth provenance classes, graphical-geometry policy, split boundaries,
deterministic fusion rules, and deferred musical surface. It contains no model,
optimizer, trainer, dataloader, checkpoint loader, or TEST evaluation path.
"""

